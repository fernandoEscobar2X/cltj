export const categoryLabel = (id) => portfolioCategories.find((c) => c.id === id)?.label ?? "";

export const portfolioItems = items.map((item) => {
  const m = media[item.id];
  return {
    ...item,
    media: item.id,
    categoryLabel: categoryLabel(item.category),
    width: m.w,
    height: m.h,
    // URL absoluta-able de la versión más grande (para JSON-LD y Open Graph).
    src: `/media/${item.id}-${m.widths.at(-1)}.${m.v}.webp`,
  };
});

export const featuredPortfolio = portfolioItems.filter((item) => item.featured);
